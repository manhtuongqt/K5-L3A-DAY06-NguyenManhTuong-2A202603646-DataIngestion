class ContentTests(unittest.TestCase):
    def test_normalize_unicode_and_keep_code_indentation(self):
        self.assertEqual(normalize_text("  a\u0301\r\n\tprint(1)  \r\n\r\n\r\nx"), "\u00e1\n    print(1)\n\nx")

    def test_extract_body_no_nav_no_duplicate_list_paragraph(self):
        html = '<title>T</title><nav>WRONG</nav><div class="body"><h1>Title<a class="headerlink">x</a></h1><ul><li><p>Only once</p></li></ul><pre>if x:\n    y()</pre></div>'
        _, text, _, _ = extract_html(html)
        self.assertNotIn("WRONG", text)
        self.assertEqual(text.count("Only once"), 1)
        self.assertIn("    y()", text)

    def test_missing_document_body_is_error(self):
        with self.assertRaises(ValueError):
            extract_html("<html><nav>Not a document</nav></html>")

    def test_units_contiguous_minimum_and_no_padded_tail(self):
        text = "\n\n".join(["x"*800 for _ in range(13)])
        ranges = unit_bounds(text)
        self.assertEqual("".join(text[a:b] for a,b in ranges), text)
        self.assertTrue(all(len(text[a:b].strip()) >= 1500 for a,b in ranges))

    def test_fixed_overlap_and_complete_coverage(self):
        text = "x"*1001
        ranges = fixed_ranges(text)
        self.assertEqual(ranges, [(0,500),(450,950),(900,1001)])
        with self.assertRaises(ValueError):
            fixed_ranges(text, size=50, overlap=50)

    def test_paragraph_long_block_no_text_loss_or_duplication(self):
        text = "Small title\n\n" + "word "*700 + "\n\n" + "last "*50
        ranges = paragraph_ranges(text)
        self.assertEqual("".join(text[a:b] for a,b in ranges), text)
        self.assertTrue(all(0 < b-a <= 1000 for a,b in ranges))

    def test_hit_requires_source_page_and_whole_evidence_in_one_chunk(self):
        q = {"gold_alternatives": [{"source_id":"d", "page":"p", "evidence_quote":"A complete condition."}]}
        c = {"document_id":"d", "page":"p", "text":"A complete condition."}
        self.assertTrue(is_hit(q,c))
        self.assertFalse(is_hit(q,{**c,"page":"other"}))
        self.assertFalse(is_hit(q,{**c,"document_id":"other"}))
        self.assertFalse(is_hit(q,{**c,"text":"A complete"}))

    def test_benchmark_lock_and_source_backed_filter(self):
        verify_lock()
        pages = {p["page"]:p for p in read_jsonl("data/pages.jsonl")}
        for q in read_json("benchmark/questions.json"):
            for g in q["gold_alternatives"]:
                self.assertIn(g["evidence_quote"],pages[g["page"]]["text"])
                self.assertTrue(all(pages[g["page"]]["metadata"][k]==v for k,v in q["filter"].items()))
            self.assertFalse({"document_id","source","page"} & q["filter"].keys())


class QdrantIntegrationTests(unittest.TestCase):
    """Use real model-produced vectors already generated by the index stage."""
    def test_real_vector_persistence_filter_and_obsolete_point_removal(self):
        vectors = np.load(ROOT/".local/vectors_A.npy")[:2]
        original = read_jsonl("results/chunks_A.jsonl")[:2]
        # Assign test-only category values to test filtering; benchmark metadata stays untouched.
        chunks = [{**c,"metadata":{**c["metadata"],"document_type":f"test_type_{i}"}} for i,c in enumerate(original)]
        with tempfile.TemporaryDirectory() as temp:
            store = Store(Path(temp)/"qdrant")
            self.assertEqual(store.replace("test",chunks,vectors),2)
            self.assertEqual(store.replace("test",chunks,vectors),2)
            store.close()
            reopened = Store(Path(temp)/"qdrant")
            try:
                hits = reopened.search("test",vectors[0],{"document_type":"test_type_1"})
                self.assertEqual(len(hits),1)
                self.assertEqual(hits[0]["chunk_id"],chunks[1]["chunk_id"])
                with self.assertRaises(ValueError):
                    reopened.search("test",vectors[0],{"document_id":"hidden_gold"})
                self.assertEqual(reopened.replace("test",chunks[:1],vectors[:1]),1)
                self.assertEqual(reopened.search("test",vectors[0],{"document_type":"test_type_1"}),[])
            finally:
                reopened.close()


if __name__ == "__main__":
    unittest.main()
